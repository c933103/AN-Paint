def decoded_display(value):
    import re
    value=value.strip()
    value=value[1:-1] if value.startswith('"') and value.endswith('"') else re.sub(r'\s+',' ',value)
    def escaped(match):
        code=match[1]
        return chr(int(code[1:],16)) if code.startswith('u') else {'n':'\n','t':'\t','r':'\r'}.get(code,code)
    return re.sub(r'\\(u[0-9A-Fa-f]{4}|.)',escaped,value)


def validate(data):
    if data.get('schema_version')!=1 or set(data.get('locales',{}))!={'ka','hy','az'}:
        raise ValueError('Exact three-language schema differs')
    if set(data.get('sources',{}))!=SOURCE_KEYS:
        raise ValueError('Exact canonical source inventory differs')
    source_xml=(catalogues.RES/'values/strings.xml').read_text()
    nodes={}
    for node in ET.fromstring(source_xml):
        nodes.setdefault(node.get('name'),[]).append(node)
    for key,row in data['sources'].items():
        if set(row)!={'value','attributes'} or not isinstance(row['value'],str) or not row['value']:
            raise ValueError('Incomplete source row')
        actual=nodes.get(key,[])
        if (len(actual)!=1 or actual[0].tag!='string' or len(actual[0]) or actual[0].text!=row['value']
                or actual[0].attrib!=row['attributes']):
            raise ValueError('Exact canonical source/attributes differ: '+key)
    for tag,locale in data['locales'].items():
        if set(locale)!={'values','retained','holds','context','scope'}:
            raise ValueError('Unknown or missing locale partition')
        if locale['scope']!={'P0':sorted(P0_KEYS),'P1':sorted(P1_KEYS)}:
            raise ValueError('Full92+249 identity inventory differs')
        seen=set()
        for section in ('values','retained','holds'):
            if set(locale[section])!=PARTITIONS[tag][section] or seen&set(locale[section]):
                raise ValueError('Review partition differs: '+tag+'/'+section)
            seen.update(locale[section])
            for key,row in locale[section].items():
                if row.get('previous')!=PREVIOUS[tag][key]:
                    raise ValueError('Exact prior complete target/attributes differ')
                if section=='holds':
                    if set(row)!={'previous','reason'} or not row['reason']:
                        raise ValueError('Hold must remain explicit with no accepted target')
                    continue
                if set(row)!={'target','attributes','display','previous'}:
                    raise ValueError('Changed or retained full-value schema differs')
                if not all(isinstance(row[k],str) and row[k] for k in ('target','display')):
                    raise ValueError('Empty complete target/display')
                if row['display']!=decoded_display(row['target']):
                    raise ValueError('Complete Android display differs from exact target')
                if row['attributes']!=ATTRIBUTES[tag][key]:
                    raise ValueError('Accepted resource attributes differ')
                if section=='retained' and (row['previous'] is None or row['target']!=row['previous']['value'] or row['attributes']!=row['previous']['attributes']):
                    raise ValueError('Retained text/attributes must stay byte-exact')
                if section=='values' and row['previous']=={'value':row['target'],'attributes':row['attributes']}:
                    raise ValueError('No-op cannot be claimed as a typed source edit')
        if seen!=P0_KEYS|P1_KEYS|DEPENDENCIES[tag]:
            raise ValueError('Missing priority identity or undocumented dependency')
        if set(locale['context'])!=CONTEXT_KEYS[tag] or locale['context']!=CONTEXT_EXPECTATIONS[tag]:
            raise ValueError('Consumer context must stay explicit and bounded')
    return data

def complete_string(xml, key, row, source):
    value = require_string(xml, key, row['target'], {'attributes': row['attributes']})
    if row['attributes'].get('formatted') != 'false':
        if token_contract(value) != token_contract(source['value']):
            raise ValueError('Full format token contract differs: '+key)
    else:
        if value.count('%') != source['value'].count('%'):
            raise ValueError('Literal percent count differs: '+key)
    if value.count('\\n') != source['value'].count('\\n'):
        raise ValueError('Escaped newline contract differs: '+key)
    return value


