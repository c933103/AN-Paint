def _immutable_residual_data(data):
    if type(data.get('schema_version')) is not int or data['schema_version'] != 1:
        raise ValueError('Residual schema_version must be integer 1')
    entries = []
    required = {'locale', 'key', 'target', 'previous_target', 'source', 'attributes'}
    for r in data['decisions']:
        if (not required <= r.keys() or set(r) - required - {'review'}
                or not all(isinstance(r[k], str) for k in ('locale','key','target','source'))
                or (r['previous_target'] is not None and not isinstance(r['previous_target'],str))
                or not isinstance(r['attributes'],dict)
                or not all(isinstance(k,str) and isinstance(v,str) for k,v in r['attributes'].items())
                or ('review' in r and type(r['review']) not in (str,int))):
            raise ValueError('Malformed scalar successor row')
        entries.append((r['locale'], r['key'], r['target'], r['previous_target'],
                        r['source'], tuple(r['attributes'].items()), r.get('review')))
    return data.get('schema_version'), tuple(entries)


