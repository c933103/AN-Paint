def _parse_fixture(text):
    def unique(pairs):
        result={}
        for key,value in pairs:
            if key in result: raise ValueError('Duplicate fixture key: '+key)
            result[key]=value
        return result
    return json.loads(text,object_pairs_hook=unique)


def fixture(name):
    return _parse_fixture((FIXTURES / name).read_text())


